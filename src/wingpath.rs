//! A wing lookahead along the staging paths of tight phase-1 nodes (and of nodes with one
//! move of slack).
//!
//! A node at staging distance d = moves left ("tight") can only reach a phase-1 endpoint by
//! a staging path: d moves, each decreasing the distance, the last a wide quarter turn (from
//! unstaged centres only a wide move stages them, and the wide half turns are phase-2 moves
//! in every frame), the endpoint's wing parity even. Such paths are few: on average 2.3 per
//! node 3 moves from the end, 4.4 per node 6 moves from the end (they are mostly one path
//! up to the order of commuting moves). After a path p the wings are pairable in frame f
//! when, before it, every dedge has one wing in the preimage under p of f's low slots and an
//! even number of the frame's high pieces among those wings. So per centre state (the
//! staging coordinate: the U/D and R/L colour masks) and wing parity, the distinct (frame,
//! preimage) pairs of its staging paths decide whether a tight node can still reach an
//! endpoint as far as its wings tell: 3.3 pairs per state 3 moves from the end, 6.2 per state
//! 6 moves from the end, and 99.8% (3 moves) to 99.6% (6 moves) of the tight nodes the
//! phase-1 search meets fail every pair (the centre-blind two-move test of [`crate::wing2`]
//! passes 5% of the nodes 2 moves from the end).
//!
//! A node at distance d with d + 1 moves left ("slack 1") reaches an endpoint by a path with
//! exactly one move that keeps the distance (the others decrease it): either before the
//! last move (which is then a wide quarter turn), or as the last move, from staged centres,
//! which then must be an outer quarter turn of the frame's special axis (the only moves that
//! keep the centres staged and are not phase-2 moves in that frame). Their pairs are more
//! (13 per state at distance 1, 20 to 40 at distance 3 and 4), but still fail on ~99% of the
//! nodes.
//!
//! Staging distances and paths do not depend on which colour pair is which, so a state is
//! the partition of the centre positions into three sets of 8 (its key: the two smallest
//! masks). The pairs are generated by a breadth-first search over these from the staged
//! state, up to distance `kmax` (states per distance: [`COUNT`]; pairs per state at distance
//! 6, 7 and 8: 6.5, 8.4 and 12.3), each state's pairs the union over its decreasing moves m
//! of the child's pairs with the preimage taken under m (a superset of the canonical paths'
//! pairs: commuting moves give the same preimages); the slack-1 pairs likewise from the
//! children's slack-1 pairs (decreasing moves) and tight pairs (keeping moves). They are kept
//! in an open-addressing hash table (with the slack-1 pairs up to distance 5): 0.14 GB for
//! distance <= 6, 1.24 GB for 7, 14.6 GB for 8 (10.3 GB of it pairs). Building it takes
//! little more memory than that (a layer's lists are computed from the previous layer's and
//! appended a block at a time); the table up to distance 8 takes about a minute and is saved
//! (see [`WingPaths::save`] and [`crate::solver::wing_paths`]). The test ignores the centres'
//! patterns, the canonical order and the trailing-run rule, so it is a necessary condition: a
//! node that fails it has no endpoint below it.

use crate::moves::{MOVE_PERMS, N_MOVES, WIDE_QUARTER, inverse_move};
use crate::phase1::{Frame, Staging};
use crate::simd::V32;
use crate::table::HugeBuf;

const MASK24: u32 = 0xff_ffff;

/// States per distance (unlabelled colour pairs: about a sixth of the U/D x R/L mask pairs).
pub const COUNT: [usize; 9] = [1, 3, 54, 717, 8955, 116_301, 1_506_114, 18_693_124, COUNT8];
const COUNT8: usize = 195_489_242;

/// A state's entry: its key (0: empty), and its pairs: `n[0]` for even wing parity from
/// `off`, then `n[1]` for odd. While building, the key's bits 56.. hold the state's distance.
#[derive(Clone, Copy, Default)]
#[repr(C, align(16))]
struct Slot {
    key: u64,
    off: u32,
    n: [u16; 2],
}

/// The key bits of a [`Slot`] (without the distance kept while building).
const KEY: u64 = !(15 << DIST);
const DIST: u32 = 56;

impl Slot {
    /// The distance of a state while building.
    #[inline(always)]
    fn dist(&self) -> u8 {
        (self.key >> DIST & 15) as u8
    }

    /// The moves from a state to its children one move closer (its parents in the search
    /// that found it), kept in `n` while building (until its lists are).
    #[inline(always)]
    fn down(&self) -> u32 {
        self.n[0] as u32 | (self.n[1] as u32) << 16
    }

    #[inline(always)]
    fn add_down(&mut self, m: usize) {
        let d = self.down() | 1 << m;
        self.n = [d as u16, (d >> 16) as u16];
    }
}

/// Slots after the last home slot, so that probing never wraps around.
const PAD: usize = 1 << 12;

/// An open-addressing hash table of [`Slot`]s (a power of two of them, and [`PAD`]): a key's
/// slot is the first one from its home on that holds it or is empty.
struct Hash {
    bits: u32,
    slots: HugeBuf<Slot>,
}

impl Hash {
    /// A table for `n` keys at a fill of at most `load`.
    fn new(n: usize, load: f64) -> Hash {
        Hash::with_bits(((n as f64 / load).log2().ceil() as u32).max(4))
    }

    /// The table for the wing paths of `n` states: filled at most 2/3 (distance 6 and 7: 0.39
    /// and 0.61; fuller tables are slower to search: buckets of 4 slots compared at once,
    /// filled 3/4, cost 2-3%), or 0.85 for over 50M states (distance 8: 0.80, 4.3 GB).
    fn for_states(n: usize) -> Hash {
        Hash::new(n, if n < 50_000_000 { 2.0 / 3.0 } else { 0.85 })
    }

    fn with_bits(bits: u32) -> Hash {
        assert!(bits < 32, "wing-path hash table too large");
        Hash {
            bits,
            slots: HugeBuf::zeroed((1 << bits) + PAD),
        }
    }

    #[inline(always)]
    fn home(&self, key: u64) -> usize {
        (key.wrapping_mul(0x9e37_79b9_7f4a_7c15) >> (64 - self.bits)) as usize
    }

    #[inline(always)]
    fn slot(&self, h: usize) -> &Slot {
        debug_assert!(h < self.slots.len());
        unsafe { &*self.slots.as_ptr().add(h) }
    }

    /// The slot holding `key` (comparing the stored keys' bits `mask`), or the empty slot
    /// where it would go, probing from `h`.
    #[inline(always)]
    fn find_from(&self, mut h: usize, key: u64, mask: u64) -> usize {
        loop {
            let k = self.slot(h).key;
            if k & mask == key || k == 0 {
                return h;
            }
            h += 1;
        }
    }

    #[inline(always)]
    fn find(&self, key: u64) -> usize {
        self.find_from(self.home(key), key, u64::MAX)
    }

    /// The slot of `key` while building (keys tagged with distances), if it is there.
    #[inline(always)]
    fn get_tagged(&self, key: u64) -> Option<&Slot> {
        let s = self.slot(self.find_from(self.home(key), key, KEY));
        (s.key != 0).then_some(s)
    }

    #[inline(always)]
    fn prefetch(&self, key: u64) {
        crate::table::prefetch(unsafe { self.slots.as_ptr().add(self.home(key)) });
    }

    /// Insert `key` with tag `tag` (and `off`) from its home `h` unless there; its slot and
    /// whether it is new.
    fn insert_from(&mut self, h: usize, key: u64, tag: u64, off: u32) -> (usize, bool) {
        let h = self.find_from(h, key, KEY);
        // The last slot stays empty, so that every probe ends.
        assert!(h + 1 < self.slots.len(), "wing-path hash table overflow");
        let s = &mut self.slots.as_mut_slice()[h];
        if s.key != 0 {
            return (h, false);
        }
        *s = Slot {
            key: key | tag,
            off,
            n: [0; 2],
        };
        (h, true)
    }

    /// The keys stored.
    #[cfg(test)]
    fn count(&self) -> usize {
        self.slots.as_slice().iter().filter(|s| s.key != 0).count()
    }
}

/// Per move, the byte tables of its centre-mask map and of its wing-slot preimage map.
struct Moves {
    centre: Vec<[[u32; 256]; 3]>,
    pre: Vec<[[u32; 256]; 3]>,
}

impl Moves {
    fn new() -> Moves {
        let centre = (0..N_MOVES)
            .map(|m| {
                let src = &MOVE_PERMS[m].centre_src;
                let mut dst = [0usize; 24];
                for t in 0..24 {
                    dst[src[t] as usize] = t;
                }
                byte_tables(|p| dst[p])
            })
            .collect();
        let pre = (0..N_MOVES)
            .map(|m| byte_tables(|y| MOVE_PERMS[m].wing_src[y] as usize))
            .collect();
        Moves { centre, pre }
    }

    /// The key of the state `key` after move `m`.
    #[inline(always)]
    fn apply(&self, key: u64, m: usize) -> u64 {
        let (ud, rl) = ((key >> 24) as u32 & MASK24, key as u32 & MASK24);
        let c = &self.centre[m];
        WingPaths::key(apply_bytes(c, ud), apply_bytes(c, rl))
    }

    /// Add a state's lists `l` under move `m` to `out`: their preimages, the parity flipped
    /// by a wide quarter turn.
    #[inline(always)]
    fn extend(&self, out: &mut [Vec<u32>; 2], l: [&[u32]; 2], m: usize) {
        let flip = (WIDE_QUARTER >> m & 1) as usize;
        let pre = &self.pre[m];
        for (p, lp) in l.iter().enumerate() {
            out[p ^ flip].extend(
                lp.iter()
                    .map(|&x| apply_bytes(pre, x & MASK24) | x & !MASK24),
            );
        }
    }
}

/// A state's tight lists (even, odd) at `s` in `pairs`.
#[inline(always)]
fn lists<'a>(pairs: &'a [u32], s: &Slot) -> [&'a [u32]; 2] {
    let (o, e, d) = (s.off as usize, s.n[0] as usize, s.n[1] as usize);
    [&pairs[o..o + e], &pairs[o + e..o + e + d]]
}

/// A state's slack-1 lists (even, odd) at `s` in `pairs` (distance <= `smax`): after its
/// tight lists, a header (their lengths, even | odd << 16), then the lists.
#[inline(always)]
fn slack_lists<'a>(pairs: &'a [u32], s: &Slot) -> [&'a [u32]; 2] {
    let o = s.off as usize + s.n[0] as usize + s.n[1] as usize;
    let h = pairs[o] as usize;
    let (e, d) = (h & 0xffff, h >> 16);
    [&pairs[o + 1..o + 1 + e], &pairs[o + 1 + e..o + 1 + e + d]]
}

/// The lists of a chunk of states: per state its slot, offset in `pairs` and counts (even,
/// odd); per state its sorted deduplicated even then odd list.
struct Part {
    start: usize,
    states: Vec<(u32, u32, [u16; 2])>,
    pairs: Vec<u32>,
}

/// States per block of [`lists_par`] (the lists of a block are kept until appended).
const BLOCK: usize = 1 << 21;

/// The lists of the states `range` (`state(i)`: the slot, key and moves to children one move
/// closer (see [`Slot::down`]) of state i, if it is one), `f(key, down, out)` collecting a
/// state's pairs (with repeats) per parity; in parallel chunks, returned in order.
fn lists_par(
    range: std::ops::Range<usize>,
    state: impl Fn(usize) -> Option<(usize, u64, u32)> + Sync,
    f: impl Fn(u64, u32, &mut [Vec<u32>; 2]) + Sync,
) -> Vec<Part> {
    let parts = std::sync::Mutex::new(vec![]);
    let base = range.start;
    crate::par::for_chunks(range.len(), 1 << 12, |r| {
        let mut part = Part {
            start: r.start,
            states: vec![],
            pairs: vec![],
        };
        let mut out: [Vec<u32>; 2] = [vec![], vec![]];
        for i in r {
            let Some((h, key, down)) = state(base + i) else {
                continue;
            };
            out[0].clear();
            out[1].clear();
            f(key, down, &mut out);
            let off = part.pairs.len() as u32;
            let mut c = [0u16; 2];
            for (p, v) in out.iter_mut().enumerate() {
                v.sort_unstable();
                v.dedup();
                c[p] = u16::try_from(v.len()).expect("wing-path list too long");
                part.pairs.extend_from_slice(v);
            }
            part.states.push((h as u32, off, c));
        }
        parts.lock().unwrap().push(part);
    });
    let mut parts = parts.into_inner().unwrap();
    parts.sort_by_key(|p| p.start);
    parts
}

/// Append the lists `parts` to `pairs`, `put(slot, offset, counts)` per state.
fn append(pairs: &mut HugeBuf<u32>, parts: Vec<Part>, mut put: impl FnMut(usize, u32, [u16; 2])) {
    for p in parts {
        let base = pairs.len();
        assert!(
            base + p.pairs.len() <= u32::MAX as usize,
            "wing-path table: too many pairs"
        );
        pairs.grow(base + p.pairs.len());
        pairs.as_mut_slice()[base..].copy_from_slice(&p.pairs);
        for (h, off, c) in p.states {
            put(h as usize, base as u32 + off, c);
        }
    }
}

pub struct WingPaths {
    /// The largest distance with entries.
    pub kmax: u8,
    /// The largest distance with slack-1 lists.
    pub smax: u8,
    hash: Hash,
    /// Pairs: the preimage (24-bit slot set) | frame << 24.
    pairs: HugeBuf<u32>,
    /// Per frame, its high pieces.
    high: [u32; 4],
    /// The pairs of the states at distance `kmax` + 1, reduced by symmetry, if built.
    pub red: Option<Reduced>,
}

/// A symmetry of the cube that maps the solver's 27 moves onto themselves (one of the 6 that
/// fix the corner the moves never turn, D L B): its map of centre-position masks, and its
/// wing-slot permutation and inverse as gathers.
struct Sym {
    centre: [[u32; 256]; 3],
    q: V32,
    qinv: V32,
}

/// The symmetries that map the 27 moves onto themselves (by conjugation, centres and wings).
fn move_set_syms() -> Vec<Sym> {
    let g = &*crate::cube::GEO;
    let mut out = vec![];
    for inv in [1i8, -1] {
        for r in crate::cube::ROTATIONS.iter() {
            let img = |v: crate::cube::V3| crate::cube::mat_apply(r, v).map(|c| c * inv);
            let p: [usize; 24] =
                std::array::from_fn(|i| crate::cube::centre_slot(img(g.centre_pos[i])));
            let q: [usize; 24] =
                std::array::from_fn(|i| crate::cube::wing_slot(img(g.wing_pos[i])));
            // Conjugated move m': src_m'[p[t]] = p[src_m[t]] (centres; wings likewise).
            let keeps = (0..N_MOVES).all(|m| {
                let (cs, ws) = (&MOVE_PERMS[m].centre_src, &MOVE_PERMS[m].wing_src);
                (0..N_MOVES).any(|m2| {
                    let (cs2, ws2) = (&MOVE_PERMS[m2].centre_src, &MOVE_PERMS[m2].wing_src);
                    (0..24).all(|t| {
                        cs2[p[t]] as usize == p[cs[t] as usize]
                            && ws2[q[t]] as usize == q[ws[t] as usize]
                    })
                })
            });
            if keeps {
                let mut qv = V32(std::array::from_fn(|i| i as u8));
                let mut qi = qv;
                for i in 0..24 {
                    qv.0[i] = q[i] as u8;
                    qi.0[q[i]] = i as u8;
                }
                out.push(Sym {
                    centre: byte_tables(|i| p[i]),
                    q: qv,
                    qinv: qi,
                });
            }
        }
    }
    assert_eq!(out.len(), 6, "symmetries keeping the move set");
    out
}

/// The pair lists of the states at one distance, one per class under the symmetries that
/// keep the move set (its member with the least key, in that member's coordinates).
pub struct Reduced {
    hash: Hash,
    pairs: HugeBuf<u32>,
    syms: Vec<Sym>,
}

impl Reduced {
    /// The least key of the class of the state with colour masks `ud` and `rl`, and the
    /// symmetry that takes the state to that member.
    #[inline(always)]
    fn canon(&self, ud: u32, rl: u32) -> (u64, usize) {
        canon(&self.syms, ud, rl)
    }

    /// Prefetch the entry of the state with colour masks `ud` and `rl`.
    #[inline(always)]
    pub fn prefetch(&self, ud: u32, rl: u32) {
        self.hash.prefetch(self.canon(ud, rl).0);
    }
}

/// See [`Reduced::canon`].
#[inline(always)]
fn canon(syms: &[Sym], ud: u32, rl: u32) -> (u64, usize) {
    let mut best = (u64::MAX, 0);
    for (i, s) in syms.iter().enumerate() {
        let k = WingPaths::key(apply_bytes(&s.centre, ud), apply_bytes(&s.centre, rl));
        if k < best.0 {
            best = (k, i);
        }
    }
    best
}

/// Per slot (and 24..32), the byte of a 24-bit set that holds its bit.
const HI: V32 = {
    let mut t = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        t[i] = (i / 8) as u8;
        i += 1;
    }
    V32(t)
};

/// Per slot, its bit within that byte.
const BIT: V32 = {
    let mut t = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        t[i] = 1 << (i % 8);
        i += 1;
    }
    V32(t)
};

const C7F: V32 = V32([0x7f; 32]);

/// Per byte of a 24-bit set, per value, the set's image under the map `f` of positions.
fn byte_tables(f: impl Fn(usize) -> usize) -> [[u32; 256]; 3] {
    let mut t = [[0u32; 256]; 3];
    for (b, tb) in t.iter_mut().enumerate() {
        for (v, e) in tb.iter_mut().enumerate() {
            for i in 0..8 {
                if v >> i & 1 == 1 {
                    *e |= 1 << f(8 * b + i);
                }
            }
        }
    }
    t
}

#[inline(always)]
fn apply_bytes(t: &[[u32; 256]; 3], x: u32) -> u32 {
    t[0][(x & 255) as usize] | t[1][(x >> 8 & 255) as usize] | t[2][(x >> 16) as usize]
}

/// The name of the saved tables and the version of their layout.
const NAME: &str = "p1-wing";
const FORMAT: u64 = 2;

impl WingPaths {
    /// The key of a centre state with U/D and R/L colour masks `ud` and `rl` (either two of
    /// the three colour-pair masks): the two smallest of the three masks. Staging distances
    /// and paths, and so the pairs, do not depend on which colour pair is which.
    #[inline(always)]
    fn key(ud: u32, rl: u32) -> u64 {
        let fb = !(ud | rl) & MASK24;
        let (a, b) = (ud.min(rl), ud.max(rl));
        let (b, c) = (b.min(fb), b.max(fb));
        let _ = c;
        let (a, b) = (a.min(b), a.max(b));
        1 << 63 | (a as u64) << 24 | b as u64
    }

    /// The slot holding `key`, or the empty slot where it would go.
    #[inline(always)]
    fn find(&self, key: u64) -> usize {
        self.hash.find(key)
    }

    /// The pairs of the staging paths of every state up to distance `kmax` (<= 8; 8: ~15 GB),
    /// and of the slack-1 paths of every state up to distance `smax` (<= `kmax`), for
    /// `frames`; `red`: also of the states at distance `kmax` + 1, reduced by symmetry (see
    /// [`Reduced`]).
    ///
    /// Layer by layer (distance k): the states at k are inserted (the children of those at
    /// k - 1 not in the table yet, one at a time: the table is the same on every run), then
    /// their lists computed from their children at k - 1 (and for slack-1 lists, at k) in
    /// parallel and appended to the pairs a block at a time.
    pub fn new(frames: &[Frame; 3], kmax: u8, smax: u8, red: bool) -> WingPaths {
        assert!((1..=8).contains(&kmax) && smax <= kmax);
        let mv = Moves::new();
        let low: [u32; 3] =
            std::array::from_fn(|f| frames[f].low_slots.iter().fold(0, |a, &s| a | 1 << s));
        let states: usize = COUNT[..=kmax as usize].iter().sum();
        let mut w = WingPaths {
            kmax,
            smax,
            hash: Hash::for_states(states),
            pairs: HugeBuf::zeroed(0),
            high: Self::high(frames),
            red: None,
        };
        let ax = Staging::axis_masks();
        let key0 = Self::key(ax[0], ax[1]);
        let (h0, _) = w.hash.insert_from(w.hash.home(key0), key0, 0, 0);
        // The slots of the states at the current distance (of the last one only if it has
        // slack-1 lists: else its states are found by a scan of the table).
        let mut layer = vec![h0 as u32];
        let mut stored = 1;
        let debug = std::env::var_os("EGGG_DEBUG").is_some();
        for k in 0..=kmax {
            let t0 = std::time::Instant::now();
            if k > 0 {
                let listed = k < kmax || k <= smax;
                let (next, n) = w.discover(&mv, &layer, k, listed);
                layer = next;
                stored += n;
                assert!(
                    stored * 10 < w.hash.slots.len() * 9,
                    "wing-path table too full"
                );
            }
            let t1 = std::time::Instant::now();
            if k <= smax {
                w.small_layer(&mv, frames, &low, &layer, k);
            } else {
                w.big_layer(&mv, (k < kmax).then_some(&layer[..]), k);
            }
            if debug {
                eprintln!(
                    "  wing paths, distance {k}: {} states, {:.2} s, lists {:.2} s, {} pairs",
                    stored,
                    (t1 - t0).as_secs_f64(),
                    t1.elapsed().as_secs_f64(),
                    w.pairs.len()
                );
            }
        }
        drop(layer);
        // The keys without distances.
        let slots = w.hash.slots.as_mut_slice().as_mut_ptr() as usize;
        crate::par::for_chunks(w.hash.slots.len(), 1 << 16, |r| {
            for h in r {
                // SAFETY: the chunks are disjoint.
                unsafe { (*(slots as *mut Slot).add(h)).key &= KEY };
            }
        });
        let n = w.pairs.len();
        w.pairs.truncate(n);
        if red {
            w.red = Some(w.reduced_layer(&mv));
        }
        w
    }

    /// Per frame, its high pieces.
    fn high(frames: &[Frame; 3]) -> [u32; 4] {
        [
            frames[0].high_pieces,
            frames[1].high_pieces,
            frames[2].high_pieces,
            0,
        ]
    }

    /// Insert the states at distance `k` (the children of the states at `parents`, at k - 1,
    /// not in the table yet), in order, with their moves to the parents (see [`Slot::down`]);
    /// their slots if `listed` (each slot's `off` then holds its index there), and their
    /// number.
    fn discover(&mut self, mv: &Moves, parents: &[u32], k: u8, listed: bool) -> (Vec<u32>, usize) {
        let tag = (k as u64) << DIST;
        let mut out = Vec::with_capacity(if listed { COUNT[k as usize] } else { 0 });
        let mut n = 0;
        // The children of a batch of parents, their homes prefetched a few ahead.
        const AHEAD: usize = 16;
        let mut buf: Vec<(u64, usize, usize)> = Vec::with_capacity(256 * N_MOVES);
        for ps in parents.chunks(256) {
            buf.clear();
            for &p in ps {
                let key = self.hash.slot(p as usize).key & KEY;
                for m in 0..N_MOVES {
                    let c = mv.apply(key, m);
                    buf.push((c, self.hash.home(c), inverse_move(m)));
                }
            }
            for i in 0..buf.len() {
                if let Some(&(_, h, _)) = buf.get(i + AHEAD) {
                    crate::table::prefetch(unsafe { self.hash.slots.as_ptr().add(h) });
                }
                let (c, h, mi) = buf[i];
                let (h, new) = self.hash.insert_from(h, c, tag, out.len() as u32);
                let s = &mut self.hash.slots.as_mut_slice()[h];
                if s.dist() == k {
                    s.add_down(mi);
                }
                if new {
                    n += 1;
                    if listed {
                        out.push(h as u32);
                    }
                }
            }
        }
        (out, n)
    }

    /// Collect the tight pairs of the state `key` at distance `k` >= 1 into `out`: its
    /// children at k - 1 under its moves `down` (from distance 1, wide quarter turns only),
    /// their lists' preimages under the move.
    #[inline(always)]
    fn tight_pairs(&self, mv: &Moves, key: u64, down: u32, k: u8, out: &mut [Vec<u32>; 2]) {
        let mut cs = [(0u64, 0usize); N_MOVES];
        let mut n = 0;
        let mut b = if k == 1 { down & WIDE_QUARTER } else { down };
        while b != 0 {
            let m = b.trailing_zeros() as usize;
            b &= b - 1;
            let c = mv.apply(key, m);
            self.hash.prefetch(c);
            cs[n] = (c, m);
            n += 1;
        }
        let pairs = self.pairs.as_slice();
        for &(c, m) in &cs[..n] {
            let s = self.hash.get_tagged(c).expect("a child one move closer");
            debug_assert_eq!(s.dist() + 1, k);
            mv.extend(out, lists(pairs, s), m);
        }
    }

    /// The lists of the states at distance `k` > `smax` (at `layer`, or found by a scan of
    /// the table), appended to the pairs: tight lists only.
    fn big_layer(&mut self, mv: &Moves, layer: Option<&[u32]>, k: u8) {
        let n = layer.map_or(self.hash.slots.len(), |l| l.len());
        for start in (0..n).step_by(BLOCK) {
            let parts = {
                let w = &*self;
                let state = |i: usize| {
                    let h = layer.map_or(i, |l| l[i] as usize);
                    let s = w.hash.slot(h);
                    (s.key != 0 && s.dist() == k).then_some((h, s.key & KEY, s.down()))
                };
                lists_par(start..(start + BLOCK).min(n), state, |key, down, out| {
                    w.tight_pairs(mv, key, down, k, out)
                })
            };
            let slots = self.hash.slots.as_mut_slice();
            append(&mut self.pairs, parts, |h, off, c| {
                slots[h].off = off;
                slots[h].n = c;
            });
        }
    }

    /// The lists of the states at distance `k` <= `smax` (at `layer`; each slot's `off` holds
    /// its index there), appended to the pairs: tight lists, a header and slack-1 lists.
    fn small_layer(
        &mut self,
        mv: &Moves,
        frames: &[Frame; 3],
        low: &[u32; 3],
        layer: &[u32],
        k: u8,
    ) {
        let key = |i: usize| {
            let s = self.hash.slot(layer[i] as usize);
            Some((i, s.key & KEY, s.down()))
        };
        // Tight lists (from the staged state: the low slots of each frame).
        let mut tight = HugeBuf::zeroed(0);
        let mut at = vec![(0u32, [0u16; 2]); layer.len()];
        let parts = lists_par(0..layer.len(), key, |key, down, out| {
            if k == 0 {
                out[0].extend((0..3).map(|f| low[f] | (f as u32) << 24));
            } else {
                self.tight_pairs(mv, key, down, k, out);
            }
        });
        append(&mut tight, parts, |i, off, c| at[i] = (off, c));
        // Slack-1 lists: from a staged state, one outer quarter turn of the frame's special
        // axis (the moves that keep the centres staged and are not phase-2 moves in the
        // frame); from distance k >= 1, a decreasing move to a slack-1 list or a keeping move
        // to a tight one.
        let mut slack = HugeBuf::zeroed(0);
        let mut sat = vec![(0u32, [0u16; 2]); layer.len()];
        let parts = lists_par(0..layer.len(), key, |key, _, out| {
            if k == 0 {
                for (f, fr) in frames.iter().enumerate() {
                    for m in 0..18 {
                        if m % 3 != 1 && fr.p2_mask >> m & 1 == 0 {
                            out[0].push(apply_bytes(&mv.pre[m], low[f]) | (f as u32) << 24);
                        }
                    }
                }
                return;
            }
            let pairs = self.pairs.as_slice();
            for m in 0..N_MOVES {
                match self.hash.get_tagged(mv.apply(key, m)) {
                    Some(s) if s.dist() + 1 == k => mv.extend(out, slack_lists(pairs, s), m),
                    Some(s) if s.dist() == k => {
                        let (o, [e, d]) = at[s.off as usize];
                        let (o, e, d) = (o as usize, e as usize, d as usize);
                        let t = tight.as_slice();
                        mv.extend(out, [&t[o..o + e], &t[o + e..o + e + d]], m);
                    }
                    _ => {}
                }
            }
        });
        append(&mut slack, parts, |i, off, c| sat[i] = (off, c));
        // The records: tight even, tight odd, a header (the slack-1 counts), slack-1 even,
        // slack-1 odd.
        let (t, sl) = (tight.as_slice(), slack.as_slice());
        let words: usize = t.len() + sl.len() + layer.len();
        let base = self.pairs.len();
        assert!(
            base + words <= u32::MAX as usize,
            "wing-path table: too many pairs"
        );
        self.pairs.grow(base + words);
        let pairs = &mut self.pairs.as_mut_slice()[base..];
        let mut o = 0;
        for (i, &h) in layer.iter().enumerate() {
            let ((to, [te, tn]), (so, [se, sn])) = (at[i], sat[i]);
            let s = &mut self.hash.slots.as_mut_slice()[h as usize];
            s.off = (base + o) as u32;
            s.n = [te, tn];
            let tl = (te + tn) as usize;
            pairs[o..o + tl].copy_from_slice(&t[to as usize..to as usize + tl]);
            o += tl;
            pairs[o] = se as u32 | (sn as u32) << 16;
            o += 1;
            let sl_len = (se + sn) as usize;
            pairs[o..o + sl_len].copy_from_slice(&sl[so as usize..so as usize + sl_len]);
            o += sl_len;
        }
        debug_assert_eq!(o, words);
    }

    /// The reduced lists of the states at distance `kmax` + 1 (the children of the table's
    /// states not in the table).
    fn reduced_layer(&self, mv: &Moves) -> Reduced {
        use std::sync::atomic::{AtomicU64, Ordering::Relaxed};
        // Classes per distance (about a sixth of the states; 8, 9: estimates).
        const COUNT: [usize; 10] = [
            1,
            1,
            12,
            130,
            1_520,
            19_500,
            252_000,
            3_200_000,
            33_000_000,
            160_000_000,
        ];
        let mut hash = Hash::new(COUNT[self.kmax as usize + 1], 0.5);
        let syms = move_set_syms();
        // The classes, inserted by their least key (in parallel, the keys by
        // compare-and-swap).
        let (base, len) = (
            hash.slots.as_mut_slice().as_mut_ptr() as usize,
            hash.slots.len(),
        );
        let count = AtomicU64::new(0);
        crate::par::for_chunks(self.hash.slots.len(), 1 << 14, |range| {
            for h in range {
                let c = self.hash.slot(h).key;
                if c == 0 {
                    continue;
                }
                for m in 0..N_MOVES {
                    let x = mv.apply(c, m);
                    if self.hash.slot(self.find(x)).key != 0 {
                        continue;
                    }
                    let (k, _) = canon(&syms, (x >> 24) as u32 & MASK24, x as u32 & MASK24);
                    let mut h = hash.home(k);
                    loop {
                        assert!(h + 1 < len, "reduced wing-path table overflow");
                        // SAFETY: h < the slot count; a slot's key is its first word.
                        let a = unsafe { &*((base as *const Slot).add(h) as *const AtomicU64) };
                        match a.compare_exchange(0, k, Relaxed, Relaxed) {
                            Ok(_) => {
                                count.fetch_add(1, Relaxed);
                                break;
                            }
                            Err(v) if v == k => break,
                            Err(_) => h += 1,
                        }
                    }
                }
            }
        });
        let n = count.into_inner() as usize;
        assert!(
            n * 10 < hash.slots.len() * 9,
            "reduced wing-path table too full"
        );
        let at: Vec<u32> = (0..hash.slots.len() as u32)
            .filter(|&h| hash.slot(h as usize).key != 0)
            .collect();
        // Each class member's pairs, from its children at `kmax` (via its decreasing moves).
        let pairs = self.pairs.as_slice();
        let parts = lists_par(
            0..at.len(),
            |i| Some((at[i] as usize, hash.slot(at[i] as usize).key, 0)),
            |key, _, out| {
                for m in 0..N_MOVES {
                    let s = self.hash.slot(self.find(mv.apply(key, m)));
                    if s.key != 0 {
                        mv.extend(out, lists(pairs, s), m);
                    }
                }
            },
        );
        let mut rpairs = HugeBuf::zeroed(0);
        let slots = hash.slots.as_mut_slice();
        append(&mut rpairs, parts, |h, off, c| {
            slots[h].off = off;
            slots[h].n = c;
        });
        Reduced {
            hash,
            pairs: rpairs,
            syms,
        }
    }

    /// Bytes used.
    pub fn bytes(&self) -> usize {
        let red = self
            .red
            .as_ref()
            .map_or(0, |r| r.hash.slots.byte_len() + r.pairs.byte_len());
        self.hash.slots.byte_len() + self.pairs.byte_len() + red
    }

    /// Ask the kernel to back the table with huge pages now (see
    /// [`HugeBuf::collapse`]).
    pub fn collapse(&self) {
        self.hash.slots.collapse();
        self.pairs.collapse();
        if let Some(r) = &self.red {
            r.hash.slots.collapse();
            r.pairs.collapse();
        }
    }

    /// The file name of a saved table with largest distances `kmax` and `smax`.
    pub fn file_name(kmax: u8, smax: u8) -> String {
        format!("{NAME}-k{kmax}s{smax}.tab")
    }

    /// Save the table (without the reduced lists) to `path` (see [`crate::table::save`]).
    pub fn save(&self, path: &std::path::Path) -> std::io::Result<()> {
        let head = self.head();
        // SAFETY: plain data.
        let head = unsafe { std::slice::from_raw_parts(head.as_ptr() as *const u8, 64) };
        crate::table::save_parts(
            path,
            NAME,
            &[head, self.hash.slots.as_bytes(), self.pairs.as_bytes()],
        )
    }

    /// The header of a saved table.
    fn head(&self) -> [u64; 8] {
        [
            FORMAT,
            self.kmax as u64,
            self.smax as u64,
            self.hash.bits as u64,
            self.hash.slots.len() as u64,
            self.pairs.len() as u64,
            0,
            0,
        ]
    }

    /// Load a table saved by [`WingPaths::save`] with largest distances `kmax` and `smax`
    /// (for `frames`; `red`: then build its reduced lists). Err if it is missing, of another
    /// kind or corrupt.
    pub fn load(
        path: &std::path::Path,
        frames: &[Frame; 3],
        kmax: u8,
        smax: u8,
        red: bool,
    ) -> Result<WingPaths, String> {
        let mut r = crate::table::Reader::open(path, NAME)?;
        let mut head = [0u64; 8];
        // SAFETY: plain data.
        r.read(unsafe { std::slice::from_raw_parts_mut(head.as_mut_ptr() as *mut u8, 64) })?;
        if head[..3] != [FORMAT, kmax as u64, smax as u64] {
            return Err(format!("another wing-path table: {:?}", &head[..3]));
        }
        if !(4..32).contains(&head[3]) || head[4] != (1 << head[3]) + PAD as u64 {
            return Err("bad wing-path table header".into());
        }
        if head[5] > u32::MAX as u64 || 64 + 16 * head[4] + 4 * head[5] != r.len() as u64 {
            return Err("bad wing-path table length".into());
        }
        let hash = Hash::with_bits(head[3] as u32);
        let mut slots = hash.slots;
        r.read(slots.as_bytes_mut())?;
        let mut pairs = HugeBuf::zeroed(head[5] as usize);
        r.read(pairs.as_bytes_mut())?;
        r.finish()?;
        let mut w = WingPaths {
            kmax,
            smax,
            hash: Hash {
                bits: head[3] as u32,
                slots,
            },
            pairs,
            high: Self::high(frames),
            red: None,
        };
        if red {
            w.red = Some(w.reduced_layer(&Moves::new()));
        }
        Ok(w)
    }

    /// A digest of every state's lists (order-independent: for comparing tables built
    /// differently), and per distance the states and their tight and slack-1 pairs; found by
    /// a breadth-first search over the table.
    pub fn digest(&self) -> (u64, Vec<[usize; 3]>) {
        use std::sync::atomic::{AtomicU64, AtomicUsize, Ordering::Relaxed};
        let mv = Moves::new();
        let mix = |mut z: u64| {
            z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
            z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
            z ^ (z >> 31)
        };
        let pairs = self.pairs.as_slice();
        let seen: Vec<AtomicU64> = (0..self.hash.slots.len().div_ceil(64))
            .map(|_| AtomicU64::new(0))
            .collect();
        let ax = Staging::axis_masks();
        let key0 = Self::key(ax[0], ax[1]);
        let h0 = self.find(key0);
        seen[h0 / 64].fetch_or(1 << (h0 % 64), Relaxed);
        let mut layer = vec![key0];
        let (mut total, mut stats) = (0u64, vec![]);
        for d in 0..=self.kmax {
            let sum = AtomicU64::new(0);
            let st = [AtomicUsize::new(0), AtomicUsize::new(0)];
            let next = std::sync::Mutex::new(vec![]);
            crate::par::for_chunks(layer.len(), 1 << 12, |r| {
                let (mut s, mut local) = (0u64, vec![]);
                for &key in &layer[r] {
                    let slot = self.hash.slot(self.find(key));
                    assert_eq!(slot.key, key, "state not in the wing-path table");
                    let t = lists(pairs, slot);
                    let sl = if d <= self.smax {
                        slack_lists(pairs, slot)
                    } else {
                        [&[][..], &[]]
                    };
                    let mut h = 0xcbf2_9ce4_8422_2325u64;
                    let mut eat = |w: u64| {
                        h = (h ^ w).wrapping_mul(0x100_0000_01b3).rotate_left(29);
                    };
                    eat(key);
                    eat(d as u64);
                    for l in t.iter().chain(&sl) {
                        eat(l.len() as u64);
                        for &x in *l {
                            eat(x as u64);
                        }
                    }
                    s = s.wrapping_add(mix(h));
                    st[0].fetch_add(t[0].len() + t[1].len(), Relaxed);
                    st[1].fetch_add(sl[0].len() + sl[1].len(), Relaxed);
                    if d < self.kmax {
                        for m in 0..N_MOVES {
                            let c = mv.apply(key, m);
                            let h = self.find(c);
                            if self.hash.slot(h).key == 0 {
                                continue;
                            }
                            let b = 1u64 << (h % 64);
                            if seen[h / 64].fetch_or(b, Relaxed) & b == 0 {
                                local.push(c);
                            }
                        }
                    }
                }
                sum.fetch_add(s, Relaxed);
                next.lock().unwrap().extend(local);
            });
            stats.push([layer.len(), st[0].load(Relaxed), st[1].load(Relaxed)]);
            total = total.wrapping_add(sum.into_inner());
            layer = next.into_inner().unwrap();
        }
        (total, stats)
    }

    /// Can a node at staging distance = moves left (<= `kmax`) with U/D and R/L colour masks
    /// `ud` and `rl`, wing positions `pos` and wing parity `odd` reach an endpoint, as far as
    /// the wings after its staging paths tell?
    #[inline(always)]
    pub fn possible(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        let s = self.hash.slot(self.find(Self::key(ud, rl)));
        if s.key == 0 {
            debug_assert!(false, "state not in the table");
            return true;
        }
        let (off, n) = if odd {
            (s.off as usize + s.n[0] as usize, s.n[1] as usize)
        } else {
            (s.off as usize, s.n[0] as usize)
        };
        self.any_pairable(off, n, pos)
    }

    /// Prefetch the entry of the state with colour masks `ud` and `rl`.
    #[inline(always)]
    pub fn prefetch(&self, ud: u32, rl: u32) {
        self.hash.prefetch(Self::key(ud, rl));
    }

    /// [`WingPaths::possible`] for a node at distance = moves left - 1 (<= `smax`): its paths
    /// have one move that keeps the distance (at the end: an outer quarter turn of the
    /// frame's special axis from staged centres).
    #[inline(always)]
    pub fn possible_slack(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        let s = self.hash.slot(self.find(Self::key(ud, rl)));
        if s.key == 0 {
            debug_assert!(false, "state not in the table");
            return true;
        }
        let o = s.off as usize + s.n[0] as usize + s.n[1] as usize;
        let h = unsafe { *self.pairs.as_ptr().add(o) } as usize;
        let (off, n) = if odd {
            (o + 1 + (h & 0xffff), h >> 16)
        } else {
            (o + 1, h & 0xffff)
        };
        self.any_pairable(off, n, pos)
    }

    /// Are the wings `pos` pairable w.r.t. one of the `n` pairs from `off`?
    #[inline(always)]
    fn any_pairable(&self, off: usize, n: usize, pos: &V32) -> bool {
        any_pairable(self.pairs.as_slice(), &self.high, off, n, pos)
    }

    /// [`WingPaths::possible`] for a node at distance `kmax` + 1, by the reduced lists.
    #[inline(always)]
    pub fn possible_red(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        let r = self.red.as_ref().unwrap();
        let (k, si) = r.canon(ud, rl);
        let s = r.hash.slot(r.hash.find(k));
        if s.key == 0 {
            debug_assert!(false, "state not in the reduced table");
            return true;
        }
        let (off, n) = if odd {
            (s.off as usize + s.n[0] as usize, s.n[1] as usize)
        } else {
            (s.off as usize, s.n[0] as usize)
        };
        // The wings of the class member: piece q(w) at slot q(pos(w)).
        let sym = unsafe { r.syms.get_unchecked(si) };
        let p = crate::simd::gather(&sym.q, &crate::simd::gather(pos, &sym.qinv));
        any_pairable(r.pairs.as_slice(), &self.high, off, n, &p)
    }
}

/// Are the wings `pos` pairable w.r.t. one of the `n` pairs of `pairs` from `off` (frames'
/// high pieces `high`)?
#[inline(always)]
fn any_pairable(pairs: &[u32], high: &[u32; 4], off: usize, n: usize, pos: &V32) -> bool {
    use crate::simd::{add, and, gather, movemask, shuf};
    if n == 0 {
        return false;
    }
    // Per wing, the byte of a slot set with its slot's bit, and the bit.
    let hi = gather(&HI, pos);
    let bit = gather(&BIT, pos);
    for &x in unsafe { pairs.get_unchecked(off..off + n) } {
        // The wings whose slot is in the preimage (bit 7 of each byte after the add).
        let v = V32(unsafe { std::mem::transmute::<[u32; 8], [u8; 32]>([x; 8]) });
        let m = movemask(&add(&and(&shuf(&v, &hi), &bit), &C7F)) & MASK24;
        if (m ^ (m >> 1)) & 0x55_5555 == 0x55_5555
            && (m & unsafe { high.get_unchecked((x >> 24) as usize) }).count_ones() & 1 == 0
        {
            return true;
        }
    }
    false
}


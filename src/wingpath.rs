//! A wing lookahead along the staging paths of tight phase-1 nodes.
//!
//! A node at staging distance d = moves left ("tight") can only reach a phase-1 endpoint by
//! a staging path: d moves, each decreasing the distance, the last a wide quarter turn (from
//! unstaged centres only a wide move stages them, and the wide half turns are phase-2 moves
//! in every frame), the endpoint's wing parity even. Such paths are few: on average 2.3 per
//! node 3 moves from the end, 4.4 per node 6 moves from the end (they are mostly one path
//! up to the order of commuting moves). After a path p the wings are pairable in frame f
//! when, before it, every dedge has one wing in the preimage under p of f's low slots and an
//! even number of the frame's high pieces among those wings. So per centre state (the
//! staging coordinate: the U/D and R/L colour masks) and wing parity, the distinct (frame,
//! preimage) pairs of its staging paths decide whether a tight node can still reach an
//! endpoint as far as its wings tell: 3.3 pairs per state 3 moves from the end, 6.2 per state
//! 6 moves from the end, and 99.8% (3 moves) to 99.6% (6 moves) of the tight nodes the
//! phase-1 search meets fail every pair (the centre-blind two-move test of [`crate::wing2`]
//! passes 5% of the nodes 2 moves from the end).
//!
//! The pairs are generated by a breadth-first search over the staging coordinate from the
//! staged states, up to distance `kmax` (states per distance: 18, 324, 4302, 53730, 697806,
//! 9036684), each state's pairs the union over its decreasing moves m of the child's pairs
//! with the preimage taken under m (a superset of the canonical paths' pairs: commuting
//! moves give the same preimages). They are kept in an open-addressing hash table keyed by
//! the two masks. The test ignores the centres' patterns, the canonical order and the
//! trailing-run rule, so it is a necessary condition: a tight node that fails it has no
//! endpoint below it.

use crate::moves::{MOVE_PERMS, N_MOVES, WIDE_QUARTER, inverse_move};
use crate::phase1::{Frame, Staging};
use crate::simd::V32;

const MASK24: u32 = 0xff_ffff;

/// A state's entry: its key (0: empty), and its pairs: `n[0]` for even wing parity from
/// `off`, then `n[1]` for odd.
#[derive(Clone, Copy, Default)]
#[repr(C, align(16))]
struct Slot {
    key: u64,
    off: u32,
    n: [u16; 2],
}

pub struct WingPaths {
    /// The largest distance with entries.
    pub kmax: u8,
    shift: u32,
    mask: usize,
    slots: Vec<Slot>,
    /// Pairs: the preimage (24-bit slot set) | frame << 24.
    pairs: Vec<u32>,
    /// Per frame, its high pieces.
    high: [u32; 4],
}

/// Per slot (and 24..32), the byte of a 24-bit set that holds its bit.
const HI: V32 = {
    let mut t = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        t[i] = (i / 8) as u8;
        i += 1;
    }
    V32(t)
};

/// Per slot, its bit within that byte.
const BIT: V32 = {
    let mut t = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        t[i] = 1 << (i % 8);
        i += 1;
    }
    V32(t)
};

const C7F: V32 = V32([0x7f; 32]);

/// Per byte of a 24-bit set, per value, the set's image under the map `f` of positions.
fn byte_tables(f: impl Fn(usize) -> usize) -> [[u32; 256]; 3] {
    let mut t = [[0u32; 256]; 3];
    for (b, tb) in t.iter_mut().enumerate() {
        for (v, e) in tb.iter_mut().enumerate() {
            for i in 0..8 {
                if v >> i & 1 == 1 {
                    *e |= 1 << f(8 * b + i);
                }
            }
        }
    }
    t
}

#[inline(always)]
fn apply_bytes(t: &[[u32; 256]; 3], x: u32) -> u32 {
    t[0][(x & 255) as usize] | t[1][(x >> 8 & 255) as usize] | t[2][(x >> 16) as usize]
}

impl WingPaths {
    #[inline(always)]
    fn key(ud: u32, rl: u32) -> u64 {
        1 << 63 | (ud as u64) << 24 | rl as u64
    }

    #[inline(always)]
    fn slot_of(&self, key: u64) -> usize {
        (key.wrapping_mul(0x9e37_79b9_7f4a_7c15) >> self.shift) as usize
    }

    /// The slot holding `key`, or the empty slot where it would go.
    #[inline(always)]
    fn find(&self, key: u64) -> usize {
        let mut h = self.slot_of(key);
        loop {
            let k = unsafe { self.slots.get_unchecked(h) }.key;
            if k == key || k == 0 {
                return h;
            }
            h = (h + 1) & self.mask;
        }
    }

    /// The pairs of the staging paths of every state up to distance `kmax` (<= 7), for
    /// `frames`.
    pub fn new(frames: &[Frame; 3], kmax: u8) -> WingPaths {
        assert!((1..=7).contains(&kmax));
        // States per distance (see the module documentation; 7: an estimate).
        const COUNT: [usize; 8] = [6, 18, 324, 4302, 53730, 697806, 9036684, 120_000_000];
        let total: usize = COUNT[..=kmax as usize].iter().sum();
        let bits = (total * 3 / 2).next_power_of_two().trailing_zeros().max(4);
        let mut w = WingPaths {
            kmax,
            shift: 64 - bits,
            mask: (1 << bits) - 1,
            slots: vec![Slot::default(); 1 << bits],
            pairs: vec![],
            high: [
                frames[0].high_pieces,
                frames[1].high_pieces,
                frames[2].high_pieces,
                0,
            ],
        };
        // Per move: the centre-mask map, and the wing-slot preimage map.
        let centre: Vec<[[u32; 256]; 3]> = (0..N_MOVES)
            .map(|m| {
                let src = &MOVE_PERMS[m].centre_src;
                let mut dst = [0usize; 24];
                for t in 0..24 {
                    dst[src[t] as usize] = t;
                }
                byte_tables(|p| dst[p])
            })
            .collect();
        let pre: Vec<[[u32; 256]; 3]> = (0..N_MOVES)
            .map(|m| byte_tables(|y| MOVE_PERMS[m].wing_src[y] as usize))
            .collect();
        // Distance 0: the staged states, each frame's low slots for even parity. During the
        // search, a slot's `off` holds its state's distance.
        struct Entry {
            key: u64,
            off: u32,
            n: [u16; 2],
        }
        let ax = Staging::axis_masks();
        let low: Vec<u32> = frames
            .iter()
            .map(|f| f.low_slots.iter().fold(0, |a, &s| a | 1 << s))
            .collect();
        let mut prev: Vec<Entry> = vec![];
        for a in 0..3 {
            for b in 0..3 {
                if a != b {
                    let key = Self::key(ax[a], ax[b]);
                    let off = w.pairs.len() as u32;
                    w.pairs.extend((0..3).map(|f| low[f] | (f as u32) << 24));
                    prev.push(Entry {
                        key,
                        off,
                        n: [3, 0],
                    });
                }
            }
        }
        prev.sort_by_key(|e| e.key);
        let mut all: Vec<Entry> = vec![];
        for e in &prev {
            let h = w.find(e.key);
            w.slots[h] = Slot {
                key: e.key,
                off: 0,
                n: [0; 2],
            };
        }
        for k in 1..=kmax as u32 {
            // (state, index of the child in `prev`, the decreasing move from the state to the
            // child, or N_MOVES if it cannot be a path's move).
            let mut links: Vec<(u64, u32, u8)> = vec![];
            for (ci, c) in prev.iter().enumerate() {
                let (ud, rl) = ((c.key >> 24) as u32 & MASK24, c.key as u32 & MASK24);
                for (m, t) in centre.iter().enumerate() {
                    let key = Self::key(apply_bytes(t, ud), apply_bytes(t, rl));
                    let h = w.find(key);
                    let s = &mut w.slots[h];
                    if s.key == 0 {
                        *s = Slot {
                            key,
                            off: k,
                            n: [0; 2],
                        };
                    } else if s.off != k {
                        continue;
                    }
                    // The state's move to the child; the last move must be a wide quarter turn.
                    let mi = inverse_move(m);
                    let ok = k > 1 || WIDE_QUARTER >> mi & 1 == 1;
                    links.push((key, ci as u32, if ok { mi as u8 } else { N_MOVES as u8 }));
                }
            }
            links.sort_unstable();
            let mut cur: Vec<Entry> = vec![];
            let mut i = 0;
            let mut buf: [Vec<u32>; 2] = [vec![], vec![]];
            while i < links.len() {
                let key = links[i].0;
                buf[0].clear();
                buf[1].clear();
                while i < links.len() && links[i].0 == key {
                    let (_, ci, mi) = links[i];
                    i += 1;
                    if mi as usize == N_MOVES {
                        continue;
                    }
                    let c = &prev[ci as usize];
                    let flip = (WIDE_QUARTER >> mi & 1) as usize;
                    let t = &pre[mi as usize];
                    let mut o = c.off as usize;
                    for cp in 0..2 {
                        for _ in 0..c.n[cp] {
                            let x = w.pairs[o];
                            o += 1;
                            buf[cp ^ flip].push(apply_bytes(t, x & MASK24) | x & !MASK24);
                        }
                    }
                }
                let off = w.pairs.len() as u32;
                let mut n = [0u16; 2];
                for (p, b) in buf.iter_mut().enumerate() {
                    b.sort_unstable();
                    b.dedup();
                    n[p] = b.len() as u16;
                    w.pairs.extend_from_slice(b);
                }
                cur.push(Entry { key, off, n });
            }
            all.append(&mut prev);
            prev = cur;
        }
        all.append(&mut prev);
        for e in &all {
            let h = w.find(e.key);
            debug_assert_eq!(w.slots[h].key, e.key);
            w.slots[h].off = e.off;
            w.slots[h].n = e.n;
        }
        w.pairs.shrink_to_fit();
        w
    }

    /// Bytes used.
    pub fn bytes(&self) -> usize {
        self.slots.len() * std::mem::size_of::<Slot>() + self.pairs.len() * 4
    }

    /// Can a node at staging distance = moves left (<= `kmax`) with U/D and R/L colour masks
    /// `ud` and `rl`, wing positions `pos` and wing parity `odd` reach an endpoint, as far as
    /// the wings after its staging paths tell?
    #[inline(always)]
    pub fn possible(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        use crate::simd::{add, and, gather, movemask, shuf};
        let key = Self::key(ud, rl);
        let s = unsafe { self.slots.get_unchecked(self.find(key)) };
        if s.key == 0 {
            debug_assert!(false, "state not in the table");
            return true;
        }
        let (off, n) = if odd {
            (s.off as usize + s.n[0] as usize, s.n[1] as usize)
        } else {
            (s.off as usize, s.n[0] as usize)
        };
        if n == 0 {
            return false;
        }
        // Per wing, the byte of a slot set with its slot's bit, and the bit.
        let hi = gather(&HI, pos);
        let bit = gather(&BIT, pos);
        for &x in unsafe { self.pairs.get_unchecked(off..off + n) } {
            // The wings whose slot is in the preimage (bit 7 of each byte after the add).
            let v = V32(unsafe { std::mem::transmute::<[u32; 8], [u8; 32]>([x; 8]) });
            let m = movemask(&add(&and(&shuf(&v, &hi), &bit), &C7F)) & MASK24;
            if (m ^ (m >> 1)) & 0x55_5555 == 0x55_5555
                && (m & unsafe { self.high.get_unchecked((x >> 24) as usize) }).count_ones() & 1
                    == 0
            {
                return true;
            }
        }
        false
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::moves::ALLOWED_AFTER;
    use crate::phase1::{P1State, P1Tables};
    use crate::table::Mod3Table;
    use rand::Rng;
    use rand::SeedableRng;
    use rand::seq::SliceRandom;
    use std::collections::HashMap;

    fn tables() -> P1Tables {
        P1Tables::with_table(Staging::new(), Mod3Table::from_depths(&[0]))
    }

    /// Staging distances up to `k` by a breadth-first search over centre states (P1State
    /// moves, independent of the table's construction), keyed by the colour masks.
    fn distances(t: &P1Tables, k: u8) -> HashMap<(u32, u32), u8> {
        let solved = P1State::from_cube(&crate::cube::Cube::SOLVED);
        let ax = Staging::axis_masks();
        let mut d = HashMap::new();
        let mut front = vec![];
        // The staged states: every assignment of colour pairs to axes (by relabelling
        // the solved state's masks).
        for a in 0..3 {
            for b in 0..3 {
                if a != b {
                    d.insert((ax[a], ax[b]), 0);
                    let mut s = solved;
                    for p in 0..24 {
                        let (bu, br) = (ax[a] >> p & 1, ax[b] >> p & 1);
                        s.centres.0[p] = if bu == 1 {
                            0
                        } else if br == 1 {
                            2
                        } else {
                            4
                        };
                    }
                    front.push(s);
                }
            }
        }
        for depth in 1..=k {
            let mut next = vec![];
            for s in &front {
                for m in 0..N_MOVES {
                    let c = s.apply(m, t);
                    if let std::collections::hash_map::Entry::Vacant(e) = d.entry(c.masks()) {
                        e.insert(depth);
                        next.push(c);
                    }
                }
            }
            front = next;
        }
        d
    }

    /// Does a staging path of `s` (distance `d`: each move decreasing it, the last a wide
    /// quarter turn) end with even wing parity and pairable wings in some frame?
    fn brute(t: &P1Tables, dist: &HashMap<(u32, u32), u8>, s: &P1State, d: u8) -> bool {
        if d == 0 {
            return !s.parity && t.frames.iter().any(|f| f.wings_ok(&s.pos));
        }
        (0..N_MOVES).any(|m| {
            if d == 1 && WIDE_QUARTER >> m & 1 == 0 {
                return false;
            }
            let c = s.apply(m, t);
            dist.get(&c.masks()) == Some(&(d - 1)) && brute(t, dist, &c, d - 1)
        })
    }

    /// The table agrees with a brute-force search over the staging paths, on states at
    /// distance 1..=4 (random walks back from the solved cube, kept if their distance is the
    /// walk's length), with their wings (often pairable after the walk) or random ones.
    #[test]
    fn matches_brute_force() {
        let t = tables();
        let w = WingPaths::new(&t.frames, 4);
        let dist = distances(&t, 4);
        assert_eq!(
            w.slots.iter().filter(|s| s.key != 0).count(),
            dist.len(),
            "states up to distance 4"
        );
        let mut rng = rand_xoshiro::Xoshiro256PlusPlus::seed_from_u64(11);
        let solved = P1State::from_cube(&crate::cube::Cube::SOLVED);
        let mut tested = [[0usize; 2]; 5];
        let mut passed = [[0usize; 2]; 5];
        for _ in 0..400_000 {
            let k = rng.gen_range(1..=4u8);
            let mut last = N_MOVES;
            let mut ms = vec![];
            for _ in 0..k {
                let a = ALLOWED_AFTER[last];
                let c: Vec<usize> = (0..N_MOVES).filter(|&m| a >> m & 1 == 1).collect();
                let m = *c.choose(&mut rng).unwrap();
                ms.push(m);
                last = m;
            }
            let mut s = solved;
            for &m in ms.iter().rev() {
                s = s.apply(inverse_move(m), &t);
            }
            if dist[&s.masks()] != k {
                continue;
            }
            let random = rng.gen_bool(0.5);
            if tested[k as usize][random as usize] >= 400 {
                continue;
            }
            if random {
                let mut p: Vec<u8> = (0..24).collect();
                p.shuffle(&mut rng);
                s.pos = V32::from_slice(&p);
                s.parity = crate::cube::Cube::parity(&p) == 1;
            }
            let (ud, rl) = s.masks();
            let want = brute(&t, &dist, &s, k);
            assert_eq!(w.possible(ud, rl, &s.pos, s.parity), want, "k {k} {ms:?}");
            tested[k as usize][random as usize] += 1;
            passed[k as usize][random as usize] += want as usize;
        }
        for k in 1..=4 {
            assert!(tested[k].iter().all(|&n| n == 400), "{tested:?}");
            // Walks that end with a wide quarter turn pass; random wings rarely do.
            assert!(passed[k][0] > 40 && passed[k][1] < 40, "{passed:?}");
        }
    }
}

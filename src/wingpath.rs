//! A wing lookahead along the staging paths of tight phase-1 nodes (and of nodes with one
//! move of slack).
//!
//! A node at staging distance d = moves left ("tight") can only reach a phase-1 endpoint by
//! a staging path: d moves, each decreasing the distance, the last a wide quarter turn (from
//! unstaged centres only a wide move stages them, and the wide half turns are phase-2 moves
//! in every frame), the endpoint's wing parity even. Such paths are few: on average 2.3 per
//! node 3 moves from the end, 4.4 per node 6 moves from the end (they are mostly one path
//! up to the order of commuting moves). After a path p the wings are pairable in frame f
//! when, before it, every dedge has one wing in the preimage under p of f's low slots and an
//! even number of the frame's high pieces among those wings. So per centre state (the
//! staging coordinate: the U/D and R/L colour masks) and wing parity, the distinct (frame,
//! preimage) pairs of its staging paths decide whether a tight node can still reach an
//! endpoint as far as its wings tell: 3.3 pairs per state 3 moves from the end, 6.2 per state
//! 6 moves from the end, and 99.8% (3 moves) to 99.6% (6 moves) of the tight nodes the
//! phase-1 search meets fail every pair (the centre-blind two-move test of [`crate::wing2`]
//! passes 5% of the nodes 2 moves from the end).
//!
//! A node at distance d with d + 1 moves left ("slack 1") reaches an endpoint by a path with
//! exactly one move that keeps the distance (the others decrease it): either before the
//! last move (which is then a wide quarter turn), or as the last move, from staged centres,
//! which then must be an outer quarter turn of the frame's special axis (the only moves that
//! keep the centres staged and are not phase-2 moves in that frame). Their pairs are more
//! (13 per state at distance 1, 20 to 40 at distance 3 and 4), but still fail on ~99% of the
//! nodes.
//!
//! Staging distances and paths do not depend on which colour pair is which, so a state is
//! the partition of the centre positions into three sets of 8 (its key: the two smallest
//! masks). The pairs are generated by a breadth-first search over these from the staged
//! state, up to distance `kmax` (states per distance: 3, 54, 717, 8955, 116301, 1506114,
//! ~1.9e7; 9 MB for distance <= 5, 144 MB for 6, 1.2 GB for 7, with the slack-1 pairs up to
//! distance 5), each state's pairs the union over its decreasing moves m of the child's pairs
//! with the preimage taken under m (a superset of the canonical paths' pairs: commuting
//! moves give the same preimages); the slack-1 pairs likewise from the children's slack-1
//! pairs (decreasing moves) and tight pairs (keeping moves). They are kept in an
//! open-addressing hash table. The test ignores the centres'
//! patterns, the canonical order and the trailing-run rule, so it is a necessary condition:
//! a node that fails it has no endpoint below it.

use crate::moves::{MOVE_PERMS, N_MOVES, WIDE_QUARTER, inverse_move};
use crate::phase1::{Frame, Staging};
use crate::simd::V32;

const MASK24: u32 = 0xff_ffff;

/// A state's entry: its key (0: empty), and its pairs: `n[0]` for even wing parity from
/// `off`, then `n[1]` for odd.
#[derive(Clone, Copy, Default)]
#[repr(C, align(16))]
struct Slot {
    key: u64,
    off: u32,
    n: [u16; 2],
}

pub struct WingPaths {
    /// The largest distance with entries.
    pub kmax: u8,
    /// The largest distance with slack-1 lists.
    pub smax: u8,
    shift: u32,
    mask: usize,
    slots: Vec<Slot>,
    /// Pairs: the preimage (24-bit slot set) | frame << 24.
    pairs: Vec<u32>,
    /// Per frame, its high pieces.
    high: [u32; 4],
    /// The pairs of the states at distance `kmax` + 1, reduced by symmetry, if built.
    pub red: Option<Reduced>,
}

/// A symmetry of the cube that maps the solver's 27 moves onto themselves (one of the 6 that
/// fix the corner the moves never turn, D L B): its map of centre-position masks, and its
/// wing-slot permutation and inverse as gathers.
struct Sym {
    centre: [[u32; 256]; 3],
    q: V32,
    qinv: V32,
}

/// The symmetries that map the 27 moves onto themselves (by conjugation, centres and wings).
fn move_set_syms() -> Vec<Sym> {
    let g = &*crate::cube::GEO;
    let mut out = vec![];
    for inv in [1i8, -1] {
        for r in crate::cube::ROTATIONS.iter() {
            let img = |v: crate::cube::V3| crate::cube::mat_apply(r, v).map(|c| c * inv);
            let p: [usize; 24] =
                std::array::from_fn(|i| crate::cube::centre_slot(img(g.centre_pos[i])));
            let q: [usize; 24] =
                std::array::from_fn(|i| crate::cube::wing_slot(img(g.wing_pos[i])));
            // Conjugated move m': src_m'[p[t]] = p[src_m[t]] (centres; wings likewise).
            let keeps = (0..N_MOVES).all(|m| {
                let (cs, ws) = (&MOVE_PERMS[m].centre_src, &MOVE_PERMS[m].wing_src);
                (0..N_MOVES).any(|m2| {
                    let (cs2, ws2) = (&MOVE_PERMS[m2].centre_src, &MOVE_PERMS[m2].wing_src);
                    (0..24).all(|t| {
                        cs2[p[t]] as usize == p[cs[t] as usize]
                            && ws2[q[t]] as usize == q[ws[t] as usize]
                    })
                })
            });
            if keeps {
                let mut qv = V32(std::array::from_fn(|i| i as u8));
                let mut qi = qv;
                for i in 0..24 {
                    qv.0[i] = q[i] as u8;
                    qi.0[q[i]] = i as u8;
                }
                out.push(Sym {
                    centre: byte_tables(|i| p[i]),
                    q: qv,
                    qinv: qi,
                });
            }
        }
    }
    assert_eq!(out.len(), 6, "symmetries keeping the move set");
    out
}

/// The pair lists of the states at one distance, one per class under the symmetries that
/// keep the move set (its member with the least key, in that member's coordinates).
pub struct Reduced {
    shift: u32,
    mask: usize,
    slots: Vec<Slot>,
    pairs: Vec<u32>,
    syms: Vec<Sym>,
}

impl Reduced {
    /// The least key of the class of the state with colour masks `ud` and `rl`, and the
    /// symmetry that takes the state to that member.
    #[inline(always)]
    fn canon(&self, ud: u32, rl: u32) -> (u64, usize) {
        canon(&self.syms, ud, rl)
    }

    #[inline(always)]
    fn find(&self, key: u64) -> usize {
        find_slot(&self.slots, self.shift, self.mask, key)
    }

    /// Prefetch the entry of the state with colour masks `ud` and `rl`.
    #[inline(always)]
    pub fn prefetch(&self, ud: u32, rl: u32) {
        let h = slot_of(self.canon(ud, rl).0, self.shift);
        crate::table::prefetch(unsafe { self.slots.as_ptr().add(h) });
    }
}

/// See [`Reduced::canon`].
#[inline(always)]
fn canon(syms: &[Sym], ud: u32, rl: u32) -> (u64, usize) {
    let mut best = (u64::MAX, 0);
    for (i, s) in syms.iter().enumerate() {
        let k = WingPaths::key(apply_bytes(&s.centre, ud), apply_bytes(&s.centre, rl));
        if k < best.0 {
            best = (k, i);
        }
    }
    best
}

#[inline(always)]
fn slot_of(key: u64, shift: u32) -> usize {
    (key.wrapping_mul(0x9e37_79b9_7f4a_7c15) >> shift) as usize
}

/// The slot holding `key`, or the empty slot where it would go.
#[inline(always)]
fn find_slot(slots: &[Slot], shift: u32, mask: usize, key: u64) -> usize {
    let mut h = slot_of(key, shift);
    loop {
        let k = unsafe { slots.get_unchecked(h) }.key;
        if k == key || k == 0 {
            return h;
        }
        h = (h + 1) & mask;
    }
}

/// Per slot (and 24..32), the byte of a 24-bit set that holds its bit.
const HI: V32 = {
    let mut t = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        t[i] = (i / 8) as u8;
        i += 1;
    }
    V32(t)
};

/// Per slot, its bit within that byte.
const BIT: V32 = {
    let mut t = [0u8; 32];
    let mut i = 0;
    while i < 32 {
        t[i] = 1 << (i % 8);
        i += 1;
    }
    V32(t)
};

const C7F: V32 = V32([0x7f; 32]);

/// Per byte of a 24-bit set, per value, the set's image under the map `f` of positions.
fn byte_tables(f: impl Fn(usize) -> usize) -> [[u32; 256]; 3] {
    let mut t = [[0u32; 256]; 3];
    for (b, tb) in t.iter_mut().enumerate() {
        for (v, e) in tb.iter_mut().enumerate() {
            for i in 0..8 {
                if v >> i & 1 == 1 {
                    *e |= 1 << f(8 * b + i);
                }
            }
        }
    }
    t
}

#[inline(always)]
fn apply_bytes(t: &[[u32; 256]; 3], x: u32) -> u32 {
    t[0][(x & 255) as usize] | t[1][(x >> 8 & 255) as usize] | t[2][(x >> 16) as usize]
}

/// The pair lists of the states at one distance (building a [`WingPaths`]): their keys,
/// slots, and per state its pairs for even then odd wing parity, from `off` in `pairs`.
struct Lists {
    keys: Vec<u64>,
    slots: Vec<u32>,
    off: Vec<u32>,
    n: Vec<[u16; 2]>,
    pairs: Vec<u32>,
}

impl Lists {
    fn list(&self, i: usize) -> [&[u32]; 2] {
        let (o, [e, d]) = (self.off[i] as usize, self.n[i]);
        let (e, d) = (e as usize, d as usize);
        [&self.pairs[o..o + e], &self.pairs[o + e..o + e + d]]
    }

    /// The lists of the states `keys` (at `slots`), `f(i, key, out)` collecting state i's
    /// pairs (with repeats) per parity; in parallel.
    fn build(
        keys: Vec<u64>,
        slots: Vec<u32>,
        f: impl Fn(usize, u64, &mut [Vec<u32>; 2]) + Sync,
    ) -> Lists {
        type Part = (usize, Vec<u32>, Vec<[u16; 2]>, Vec<u32>);
        let parts: std::sync::Mutex<Vec<Part>> = std::sync::Mutex::new(vec![]);
        crate::par::for_chunks(keys.len(), 1 << 14, |r| {
            let (mut off, mut n, mut pairs) = (vec![], vec![], vec![]);
            let mut out: [Vec<u32>; 2] = [vec![], vec![]];
            for i in r.clone() {
                out[0].clear();
                out[1].clear();
                f(i, keys[i], &mut out);
                off.push(pairs.len() as u32);
                let mut c = [0u16; 2];
                for (p, v) in out.iter_mut().enumerate() {
                    v.sort_unstable();
                    v.dedup();
                    c[p] = v.len() as u16;
                    pairs.extend_from_slice(v);
                }
                n.push(c);
            }
            parts.lock().unwrap().push((r.start, off, n, pairs));
        });
        let mut parts = parts.into_inner().unwrap();
        parts.sort_by_key(|p| p.0);
        let mut l = Lists {
            off: Vec::with_capacity(keys.len()),
            n: Vec::with_capacity(keys.len()),
            pairs: Vec::with_capacity(parts.iter().map(|p| p.3.len()).sum()),
            keys,
            slots,
        };
        for (_, off, n, pairs) in parts {
            let base = l.pairs.len() as u32;
            l.off.extend(off.iter().map(|&o| o + base));
            l.n.extend(n);
            l.pairs.extend(pairs);
        }
        l
    }
}

impl WingPaths {
    /// The key of a centre state with U/D and R/L colour masks `ud` and `rl` (either two of
    /// the three colour-pair masks): the two smallest of the three masks. Staging distances
    /// and paths, and so the pairs, do not depend on which colour pair is which.
    #[inline(always)]
    fn key(ud: u32, rl: u32) -> u64 {
        let fb = !(ud | rl) & MASK24;
        let (a, b) = (ud.min(rl), ud.max(rl));
        let (b, c) = (b.min(fb), b.max(fb));
        let _ = c;
        let (a, b) = (a.min(b), a.max(b));
        1 << 63 | (a as u64) << 24 | b as u64
    }

    #[inline(always)]
    fn slot_of(&self, key: u64) -> usize {
        slot_of(key, self.shift)
    }

    /// The slot holding `key`, or the empty slot where it would go.
    #[inline(always)]
    fn find(&self, key: u64) -> usize {
        find_slot(&self.slots, self.shift, self.mask, key)
    }

    /// The pairs of the staging paths of every state up to distance `kmax` (<= 7), and of
    /// the slack-1 paths of every state up to distance `smax` (<= `kmax`), for `frames`;
    /// `red`: also of the states at distance `kmax` + 1, reduced by symmetry (see
    /// [`Reduced`]).
    pub fn new(frames: &[Frame; 3], kmax: u8, smax: u8, red: bool) -> WingPaths {
        assert!((1..=7).contains(&kmax) && smax <= kmax);
        // States per distance (unlabelled colour pairs: about a sixth of the U/D x R/L mask
        // pairs; 7: an estimate).
        const COUNT: [usize; 8] = [1, 3, 54, 717, 8955, 116_301, 1_506_114, 19_200_000];
        let total: usize = COUNT[..=kmax as usize].iter().sum();
        let bits = (total * 3 / 2).next_power_of_two().trailing_zeros().max(4);
        let mut w = WingPaths {
            kmax,
            smax,
            shift: 64 - bits,
            mask: (1 << bits) - 1,
            slots: vec![Slot::default(); 1 << bits],
            pairs: vec![],
            high: [
                frames[0].high_pieces,
                frames[1].high_pieces,
                frames[2].high_pieces,
                0,
            ],
            red: None,
        };
        // Per move: the centre-mask map, and the wing-slot preimage map.
        let centre: Vec<[[u32; 256]; 3]> = (0..N_MOVES)
            .map(|m| {
                let src = &MOVE_PERMS[m].centre_src;
                let mut dst = [0usize; 24];
                for t in 0..24 {
                    dst[src[t] as usize] = t;
                }
                byte_tables(|p| dst[p])
            })
            .collect();
        let pre: Vec<[[u32; 256]; 3]> = (0..N_MOVES)
            .map(|m| byte_tables(|y| MOVE_PERMS[m].wing_src[y] as usize))
            .collect();
        let apply = |key: u64, m: usize| {
            let (ud, rl) = ((key >> 24) as u32 & MASK24, key as u32 & MASK24);
            Self::key(apply_bytes(&centre[m], ud), apply_bytes(&centre[m], rl))
        };
        // A list's pairs under a move: their preimages, the parity flipped by a wide quarter
        // turn.
        let extend = |out: &mut [Vec<u32>; 2], l: [&[u32]; 2], m: usize| {
            let flip = (WIDE_QUARTER >> m & 1) as usize;
            for (p, lp) in l.iter().enumerate() {
                out[p ^ flip].extend(
                    lp.iter()
                        .map(|&x| apply_bytes(&pre[m], x & MASK24) | x & !MASK24),
                );
            }
        };
        let low: Vec<u32> = frames
            .iter()
            .map(|f| f.low_slots.iter().fold(0, |a, &s| a | 1 << s))
            .collect();
        // While building, a slot's `off` holds its state's distance and `n` its index there.
        let at = |w: &WingPaths, key: u64| -> Option<(u32, usize)> {
            let s = &w.slots[w.find(key)];
            (s.key != 0).then(|| (s.off, s.n[0] as usize | (s.n[1] as usize) << 16))
        };
        let ax = Staging::axis_masks();
        let key0 = Self::key(ax[0], ax[1]);
        let h0 = w.find(key0);
        w.slots[h0] = Slot {
            key: key0,
            off: 0,
            n: [0; 2],
        };
        let mut tight = vec![Lists {
            keys: vec![key0],
            slots: vec![h0 as u32],
            off: vec![0],
            n: vec![[3, 0]],
            pairs: (0..3).map(|f| low[f] | (f as u32) << 24).collect(),
        }];
        for k in 1..=kmax as u32 {
            // The states at distance k (found from those at k - 1), and their links: the
            // state's index << 27 | the child's index << 5 | the state's move to the child,
            // or N_MOVES if it cannot be a staging path's move (the last move is a wide
            // quarter turn).
            let prev = &tight[k as usize - 1];
            assert!(prev.keys.len() < 1 << 22);
            let mut links: Vec<u64> = vec![];
            let (mut keys, mut slots) = (vec![], vec![]);
            for (ci, &c) in prev.keys.iter().enumerate() {
                for m in 0..N_MOVES {
                    let key = apply(c, m);
                    let h = w.find(key);
                    let s = &mut w.slots[h];
                    let i = if s.key == 0 {
                        let i = keys.len();
                        *s = Slot {
                            key,
                            off: k,
                            n: [i as u16, (i >> 16) as u16],
                        };
                        keys.push(key);
                        slots.push(h as u32);
                        i
                    } else if s.off == k {
                        s.n[0] as usize | (s.n[1] as usize) << 16
                    } else {
                        continue;
                    };
                    let mi = inverse_move(m);
                    let mi = if k > 1 || WIDE_QUARTER >> mi & 1 == 1 {
                        mi
                    } else {
                        N_MOVES
                    };
                    links.push((i as u64) << 27 | (ci as u64) << 5 | mi as u64);
                }
            }
            let states: usize = tight.iter().map(|l| l.keys.len()).sum::<usize>() + keys.len();
            assert!(states * 10 < w.slots.len() * 9, "wing-path table too full");
            links.sort_unstable();
            let mut first = vec![0u32; keys.len() + 1];
            for &l in &links {
                first[(l >> 27) as usize + 1] += 1;
            }
            for i in 0..keys.len() {
                first[i + 1] += first[i];
            }
            let lists = Lists::build(keys, slots, |i, _, out| {
                for &l in &links[first[i] as usize..first[i + 1] as usize] {
                    let (ci, mi) = ((l >> 5) as usize & ((1 << 22) - 1), (l & 31) as usize);
                    if mi < N_MOVES {
                        extend(out, prev.list(ci), mi);
                    }
                }
            });
            tight.push(lists);
        }
        // Slack-1 lists: from a staged state, one outer quarter turn of the frame's special
        // axis (the moves that keep the centres staged and are not phase-2 moves in the
        // frame); from distance k >= 1, a decreasing move to a slack-1 list or a keeping move
        // to a tight one.
        let mut slack: Vec<Lists> = vec![];
        for k in 0..=smax as usize {
            let l = &tight[k];
            let lists = Lists::build(l.keys.clone(), vec![], |_, key, out| {
                if k == 0 {
                    for (f, fr) in frames.iter().enumerate() {
                        for m in 0..18 {
                            if m % 3 != 1 && fr.p2_mask >> m & 1 == 0 {
                                out[0].push(apply_bytes(&pre[m], low[f]) | (f as u32) << 24);
                            }
                        }
                    }
                    return;
                }
                for m in 0..N_MOVES {
                    match at(&w, apply(key, m)) {
                        Some((d, j)) if d as usize + 1 == k => extend(out, slack[k - 1].list(j), m),
                        Some((d, j)) if d as usize == k => extend(out, tight[k].list(j), m),
                        _ => {}
                    }
                }
            });
            slack.push(lists);
        }
        // The pairs of a state: tight even, tight odd, and (up to `smax`) a header (the
        // slack-1 counts, even | odd << 16), slack-1 even, slack-1 odd. The largest distance
        // without slack-1 lists comes first, as built.
        let last = tight.len() - 1;
        let mut order: Vec<usize> = (0..tight.len()).collect();
        if last > smax as usize {
            order.rotate_right(1);
            w.pairs = std::mem::take(&mut tight[last].pairs);
            w.pairs.reserve(
                tight[..last].iter().map(|l| l.pairs.len()).sum::<usize>()
                    + slack
                        .iter()
                        .map(|l| l.pairs.len() + l.keys.len())
                        .sum::<usize>(),
            );
        }
        for k in order {
            let l = &tight[k];
            for i in 0..l.keys.len() {
                let off = if k == last && last > smax as usize {
                    l.off[i]
                } else {
                    let off = w.pairs.len() as u32;
                    let [e, o] = l.list(i);
                    w.pairs.extend_from_slice(e);
                    w.pairs.extend_from_slice(o);
                    if k <= smax as usize {
                        let sl = &slack[k];
                        let [e, o] = sl.list(i);
                        w.pairs.push(e.len() as u32 | (o.len() as u32) << 16);
                        w.pairs.extend_from_slice(e);
                        w.pairs.extend_from_slice(o);
                    }
                    off
                };
                let s = &mut w.slots[l.slots[i] as usize];
                debug_assert_eq!(s.key, l.keys[i]);
                s.off = off;
                s.n = l.n[i];
            }
        }
        w.pairs.shrink_to_fit();
        if red {
            let keys = std::mem::take(&mut tight[kmax as usize].keys);
            w.red = Some(w.reduced_layer(&keys, &apply, &extend));
        }
        w
    }

    /// The reduced lists of the states at distance `kmax` + 1 (`last`: the states at `kmax`;
    /// `apply` and `extend` as in [`WingPaths::new`]).
    fn reduced_layer(
        &self,
        last: &[u64],
        apply: &(impl Fn(u64, usize) -> u64 + Sync),
        extend: &(impl Fn(&mut [Vec<u32>; 2], [&[u32]; 2], usize) + Sync),
    ) -> Reduced {
        use std::sync::atomic::{AtomicU64, Ordering::Relaxed};
        // Classes per distance (about a sixth of the states; 8: an estimate).
        const COUNT: [usize; 9] = [1, 1, 12, 130, 1_520, 19_500, 252_000, 3_200_000, 33_000_000];
        let n = COUNT[self.kmax as usize + 1];
        let bits = (n * 2).next_power_of_two().trailing_zeros().max(4);
        let (shift, mask) = (64 - bits, (1usize << bits) - 1);
        let syms = move_set_syms();
        let mut slots = vec![Slot::default(); 1 << bits];
        // The classes: the children of the states at `kmax` not in the table, inserted by
        // their least key (in parallel, the keys by compare-and-swap).
        let base = slots.as_mut_ptr() as usize;
        let count = AtomicU64::new(0);
        crate::par::for_chunks(last.len(), 1 << 12, |range| {
            for &c in &last[range] {
                for m in 0..N_MOVES {
                    let x = apply(c, m);
                    if self.slots[self.find(x)].key != 0 {
                        continue;
                    }
                    let (k, _) = canon(&syms, (x >> 24) as u32 & MASK24, x as u32 & MASK24);
                    let mut h = slot_of(k, shift);
                    loop {
                        // SAFETY: h < the slot count; a slot's key is its first word.
                        let a = unsafe { &*((base as *const Slot).add(h) as *const AtomicU64) };
                        match a.compare_exchange(0, k, Relaxed, Relaxed) {
                            Ok(_) => {
                                count.fetch_add(1, Relaxed);
                                break;
                            }
                            Err(v) if v == k => break,
                            Err(_) => h = (h + 1) & mask,
                        }
                    }
                }
            }
        });
        let n = count.into_inner() as usize;
        assert!(n * 10 < slots.len() * 9, "reduced wing-path table too full");
        let (keys, at): (Vec<u64>, Vec<u32>) = slots
            .iter()
            .enumerate()
            .filter(|(_, s)| s.key != 0)
            .map(|(h, s)| (s.key, h as u32))
            .unzip();
        // Each class member's pairs, from its children at `kmax` (via its decreasing moves).
        let lists = Lists::build(keys, at, |_, key, out| {
            for m in 0..N_MOVES {
                let s = &self.slots[self.find(apply(key, m))];
                if s.key != 0 {
                    let (o, e, d) = (s.off as usize, s.n[0] as usize, s.n[1] as usize);
                    extend(
                        out,
                        [&self.pairs[o..o + e], &self.pairs[o + e..o + e + d]],
                        m,
                    );
                }
            }
        });
        for i in 0..lists.keys.len() {
            let s = &mut slots[lists.slots[i] as usize];
            s.off = lists.off[i];
            s.n = lists.n[i];
        }
        Reduced {
            shift,
            mask,
            slots,
            pairs: lists.pairs,
            syms,
        }
    }

    /// Bytes used.
    pub fn bytes(&self) -> usize {
        let red = self.red.as_ref().map_or(0, |r| {
            r.slots.len() * std::mem::size_of::<Slot>() + r.pairs.len() * 4
        });
        self.slots.len() * std::mem::size_of::<Slot>() + self.pairs.len() * 4 + red
    }

    /// Can a node at staging distance = moves left (<= `kmax`) with U/D and R/L colour masks
    /// `ud` and `rl`, wing positions `pos` and wing parity `odd` reach an endpoint, as far as
    /// the wings after its staging paths tell?
    #[inline(always)]
    pub fn possible(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        let s = unsafe { self.slots.get_unchecked(self.find(Self::key(ud, rl))) };
        if s.key == 0 {
            debug_assert!(false, "state not in the table");
            return true;
        }
        let (off, n) = if odd {
            (s.off as usize + s.n[0] as usize, s.n[1] as usize)
        } else {
            (s.off as usize, s.n[0] as usize)
        };
        self.any_pairable(off, n, pos)
    }

    /// Prefetch the entry of the state with colour masks `ud` and `rl`.
    #[inline(always)]
    pub fn prefetch(&self, ud: u32, rl: u32) {
        let h = self.slot_of(Self::key(ud, rl));
        crate::table::prefetch(unsafe { self.slots.as_ptr().add(h) });
    }

    /// [`WingPaths::possible`] for a node at distance = moves left - 1 (<= `smax`): its paths
    /// have one move that keeps the distance (at the end: an outer quarter turn of the
    /// frame's special axis from staged centres).
    #[inline(always)]
    pub fn possible_slack(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        let s = unsafe { self.slots.get_unchecked(self.find(Self::key(ud, rl))) };
        if s.key == 0 {
            debug_assert!(false, "state not in the table");
            return true;
        }
        let o = s.off as usize + s.n[0] as usize + s.n[1] as usize;
        let h = unsafe { *self.pairs.get_unchecked(o) } as usize;
        let (off, n) = if odd {
            (o + 1 + (h & 0xffff), h >> 16)
        } else {
            (o + 1, h & 0xffff)
        };
        self.any_pairable(off, n, pos)
    }

    /// Are the wings `pos` pairable w.r.t. one of the `n` pairs from `off`?
    #[inline(always)]
    fn any_pairable(&self, off: usize, n: usize, pos: &V32) -> bool {
        any_pairable(&self.pairs, &self.high, off, n, pos)
    }

    /// [`WingPaths::possible`] for a node at distance `kmax` + 1, by the reduced lists.
    #[inline(always)]
    pub fn possible_red(&self, ud: u32, rl: u32, pos: &V32, odd: bool) -> bool {
        let r = self.red.as_ref().unwrap();
        let (k, si) = r.canon(ud, rl);
        let s = unsafe { r.slots.get_unchecked(r.find(k)) };
        if s.key == 0 {
            debug_assert!(false, "state not in the reduced table");
            return true;
        }
        let (off, n) = if odd {
            (s.off as usize + s.n[0] as usize, s.n[1] as usize)
        } else {
            (s.off as usize, s.n[0] as usize)
        };
        // The wings of the class member: piece q(w) at slot q(pos(w)).
        let sym = unsafe { r.syms.get_unchecked(si) };
        let p = crate::simd::gather(&sym.q, &crate::simd::gather(pos, &sym.qinv));
        any_pairable(&r.pairs, &self.high, off, n, &p)
    }
}

/// Are the wings `pos` pairable w.r.t. one of the `n` pairs of `pairs` from `off` (frames'
/// high pieces `high`)?
#[inline(always)]
fn any_pairable(pairs: &[u32], high: &[u32; 4], off: usize, n: usize, pos: &V32) -> bool {
    use crate::simd::{add, and, gather, movemask, shuf};
    if n == 0 {
        return false;
    }
    // Per wing, the byte of a slot set with its slot's bit, and the bit.
    let hi = gather(&HI, pos);
    let bit = gather(&BIT, pos);
    for &x in unsafe { pairs.get_unchecked(off..off + n) } {
        // The wings whose slot is in the preimage (bit 7 of each byte after the add).
        let v = V32(unsafe { std::mem::transmute::<[u32; 8], [u8; 32]>([x; 8]) });
        let m = movemask(&add(&and(&shuf(&v, &hi), &bit), &C7F)) & MASK24;
        if (m ^ (m >> 1)) & 0x55_5555 == 0x55_5555
            && (m & unsafe { high.get_unchecked((x >> 24) as usize) }).count_ones() & 1 == 0
        {
            return true;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::moves::ALLOWED_AFTER;
    use crate::phase1::{P1State, P1Tables};
    use crate::table::Mod3Table;
    use rand::Rng;
    use rand::SeedableRng;
    use rand::seq::SliceRandom;
    use std::collections::HashMap;

    fn tables() -> P1Tables {
        P1Tables::with_table(Staging::new(), Mod3Table::from_depths(&[0]))
    }

    /// Staging distances up to `k` by a breadth-first search over centre states (P1State
    /// moves, independent of the table's construction), keyed by the colour masks.
    fn distances(t: &P1Tables, k: u8) -> HashMap<(u32, u32), u8> {
        let solved = P1State::from_cube(&crate::cube::Cube::SOLVED);
        let ax = Staging::axis_masks();
        let mut d = HashMap::new();
        let mut front = vec![];
        // The staged states: every assignment of colour pairs to axes (by relabelling
        // the solved state's masks).
        for a in 0..3 {
            for b in 0..3 {
                if a != b {
                    d.insert((ax[a], ax[b]), 0);
                    let mut s = solved;
                    for p in 0..24 {
                        let (bu, br) = (ax[a] >> p & 1, ax[b] >> p & 1);
                        s.centres.0[p] = if bu == 1 {
                            0
                        } else if br == 1 {
                            2
                        } else {
                            4
                        };
                    }
                    front.push(s);
                }
            }
        }
        for depth in 1..=k {
            let mut next = vec![];
            for s in &front {
                for m in 0..N_MOVES {
                    let c = s.apply(m, t);
                    if let std::collections::hash_map::Entry::Vacant(e) = d.entry(c.masks()) {
                        e.insert(depth);
                        next.push(c);
                    }
                }
            }
            front = next;
        }
        d
    }

    /// Can `s` (staging distance `d`, `left` >= `d` moves left) reach an endpoint in
    /// exactly `left` moves, as far as the wings tell (centre patterns, canonical order and
    /// trailing runs ignored)? Each move must keep the distance within reach; the last one
    /// stages the centres (or keeps them staged), is not a phase-2 move of a frame in which
    /// the wings are then pairable, and leaves the wing parity even.
    fn brute(t: &P1Tables, dist: &HashMap<(u32, u32), u8>, s: &P1State, left: u8) -> bool {
        (0..N_MOVES).any(|m| {
            let c = s.apply(m, t);
            let Some(&dc) = dist.get(&c.masks()) else {
                return false;
            };
            if left == 1 {
                dc == 0
                    && !c.parity
                    && t.frames
                        .iter()
                        .any(|f| f.p2_mask >> m & 1 == 0 && f.wings_ok(&c.pos))
            } else {
                dc < left && brute(t, dist, &c, left - 1)
            }
        })
    }

    /// The table agrees with a brute-force search, for tight states at distance 1..=4 and
    /// slack-1 states at distance 0..=4 (random walks back from the solved cube, kept if their
    /// distance is the walk's length, or one less), with their wings (often pairable after
    /// the walk) or random ones.
    #[test]
    fn matches_brute_force() {
        let t = tables();
        let w = WingPaths::new(&t.frames, 5, 4, false);
        let dist = distances(&t, 5);
        let keys: std::collections::HashSet<u64> = dist
            .keys()
            .map(|&(ud, rl)| WingPaths::key(ud, rl))
            .collect();
        assert_eq!(
            w.slots.iter().filter(|s| s.key != 0).count(),
            keys.len(),
            "states up to distance 5"
        );
        let mut rng = rand_xoshiro::Xoshiro256PlusPlus::seed_from_u64(11);
        let solved = P1State::from_cube(&crate::cube::Cube::SOLVED);
        // [slack][moves left][random wings]
        let mut tested = [[[0usize; 2]; 6]; 2];
        let mut passed = [[[0usize; 2]; 6]; 2];
        for _ in 0..1_000_000 {
            let left = rng.gen_range(1..=5u8);
            let mut last = N_MOVES;
            let mut ms = vec![];
            for _ in 0..left {
                let a = ALLOWED_AFTER[last];
                let c: Vec<usize> = (0..N_MOVES).filter(|&m| a >> m & 1 == 1).collect();
                let m = *c.choose(&mut rng).unwrap();
                ms.push(m);
                last = m;
            }
            let mut s = solved;
            for &m in ms.iter().rev() {
                s = s.apply(inverse_move(m), &t);
            }
            let d = dist[&s.masks()];
            if d + 1 < left || (d == left && d == 5) {
                continue;
            }
            let slack = (left - d) as usize;
            let random = rng.gen_bool(0.5);
            if tested[slack][left as usize][random as usize] >= 300 {
                continue;
            }
            if random {
                let mut p: Vec<u8> = (0..24).collect();
                p.shuffle(&mut rng);
                s.pos = V32::from_slice(&p);
                s.parity = crate::cube::Cube::parity(&p) == 1;
            }
            let (ud, rl) = s.masks();
            let want = brute(&t, &dist, &s, left);
            let got = if slack == 0 {
                w.possible(ud, rl, &s.pos, s.parity)
            } else {
                w.possible_slack(ud, rl, &s.pos, s.parity)
            };
            assert_eq!(got, want, "slack {slack} left {left} {ms:?}");
            tested[slack][left as usize][random as usize] += 1;
            passed[slack][left as usize][random as usize] += want as usize;
        }
        for slack in 0..2 {
            for left in 1 + slack..=5 {
                if slack == 0 && left == 5 {
                    continue;
                }
                let (n, p) = (tested[slack][left], passed[slack][left]);
                assert!(n.iter().all(|&x| x == 300), "{tested:?}");
                // Walks pass often (those that end at an endpoint); random wings rarely.
                assert!(
                    p[0] > 30 && p[1] < 60,
                    "slack {slack} left {left}: {passed:?}"
                );
            }
        }
    }

    /// The symmetry-reduced lists one move beyond the table (distance 4 after a table up to
    /// 3, and 5 after 4) agree with the full table's on states at that distance (random
    /// walks back from the solved cube) with their wings or random ones.
    #[test]
    fn reduced_layer_matches_full_table() {
        let t = tables();
        let full = WingPaths::new(&t.frames, 5, 0, false);
        let dist = distances(&t, 5);
        let mut rng = rand_xoshiro::Xoshiro256PlusPlus::seed_from_u64(12);
        let solved = P1State::from_cube(&crate::cube::Cube::SOLVED);
        for k in [4u8, 5] {
            let w = WingPaths::new(&t.frames, k - 1, 0, true);
            let r = w.red.as_ref().unwrap();
            let classes = r.slots.iter().filter(|s| s.key != 0).count();
            let states = full.slots.iter().filter(|s| s.key != 0).count();
            assert!(classes * 5 < states, "{classes} classes");
            let (mut n, mut pass) = (0, [0usize; 2]);
            while n < 3000 {
                let mut s = solved;
                for _ in 0..k {
                    s = s.apply(rng.gen_range(0..N_MOVES), &t);
                }
                if dist[&s.masks()] != k {
                    continue;
                }
                let random = n % 2 == 1;
                if random {
                    let mut p: Vec<u8> = (0..24).collect();
                    p.shuffle(&mut rng);
                    s.pos = V32::from_slice(&p);
                    s.parity = crate::cube::Cube::parity(&p) == 1;
                }
                let (ud, rl) = s.masks();
                let want = full.possible(ud, rl, &s.pos, s.parity);
                assert_eq!(
                    w.possible_red(ud, rl, &s.pos, s.parity),
                    want,
                    "k {k} case {n}"
                );
                pass[random as usize] += want as usize;
                n += 1;
            }
            assert!(pass[0] > 100, "{pass:?}");
        }
    }
}
